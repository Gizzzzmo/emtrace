"""Hatchling build hook: bake the git commit of the build into the package.

``initialize`` writes ``emtrace/_build_info.py`` (gitignored) with the commit
hash and dirty state of the tree being built. ``emtrace version`` reads it at
runtime to report the provenance of installed wheels; when run from a git
checkout it queries git directly instead.

Set ``EMTRACE_BUILD_COMMIT`` to override detection (e.g. when building from an
exported tarball whose commit is known). When git is unavailable and a
``_build_info.py`` is already present (building a wheel from an sdist), the
existing file is kept so the sdist's recorded commit survives.
"""

from __future__ import annotations

import os
import subprocess
from pathlib import Path
from typing import Any, override

from hatchling.builders.hooks.plugin.interface import BuildHookInterface

_GENERATED_NOTE = (
    '"""Generated by hatch_build.py at build time; do not edit or commit."""'
)


def _git(root: Path, *args: str) -> str | None:
    """Run git in *root*; return stripped stdout, or None on any failure."""
    try:
        proc = subprocess.run(
            ["git", *args],
            cwd=root,
            capture_output=True,
            text=True,
            check=True,
        )
    except (OSError, subprocess.CalledProcessError):
        return None
    return proc.stdout.strip()


def _resolve_commit(root: Path) -> tuple[str, bool] | None:
    """``(commit, dirty)`` of the checkout being built, or None when unknown."""
    commit = os.environ.get("EMTRACE_BUILD_COMMIT") or _git(root, "rev-parse", "HEAD")
    if commit is None:
        return None
    # -uno keeps untracked files (e.g. build outputs) from tainting the result.
    status = _git(root, "status", "--porcelain", "-uno")
    return commit, status is not None and status != ""


class EmtraceBuildHook(BuildHookInterface[Any]):
    """Bake the build's git commit into ``emtrace/_build_info.py``."""

    @override
    def initialize(self, version: str, build_data: dict[str, Any]) -> None:
        _ = version
        root = Path(self.root)
        target = root / "emtrace" / "_build_info.py"
        info = _resolve_commit(root)
        if info is not None:
            commit, dirty = info
            body = f"COMMIT: str | None = {commit!r}\nDIRTY = {dirty!r}\n"
        elif not target.exists():
            body = "COMMIT: str | None = None\nDIRTY = False\n"
        else:
            body = None  # keep the commit recorded when the sdist was created
        if body is not None:
            _ = target.write_text(f"{_GENERATED_NOTE}\n\n{body}")
        # hatchling excludes gitignored files by default; force the generated
        # module into the wheel and sdist regardless.
        _ = build_data["artifacts"].append("emtrace/_build_info.py")
